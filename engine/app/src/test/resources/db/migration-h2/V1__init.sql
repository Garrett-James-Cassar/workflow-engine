-- H2 has no partial indexes, so these are plain indexes here (performance only).
-- Test-only copy of db/migration/V1__init.sql for in-memory H2 (PostgreSQL mode).
-- The append-only trigger is PL/pgSQL and stays covered by the Testcontainers repository test (t.unit.c).

create domain jsonb as varchar(10485760);

create table instances (
    id           uuid primary key,
    definition   text        not null,
    version      int         not null,
    mode         text        not null default 'live', -- 'preview' arrives with the studio
    status       text        not null,
    current_step text,
    end_status   text,
    vars         jsonb       not null,
    created_at   timestamp with time zone not null default now(),
    updated_at   timestamp with time zone not null default now()
);

create table user_tasks (
    id            uuid primary key,
    instance_id   uuid        not null references instances (id),
    step          text        not null,
    assignee_type text        not null, -- USER | ROLE
    assignee      text        not null,
    scope         jsonb       not null,
    status        text        not null, -- OPEN | DONE
    outcome       text,
    form          jsonb,
    decided_by    text,
    decided_at    timestamp with time zone,
    created_at    timestamp with time zone not null default now()
);
create index user_tasks_open on user_tasks (instance_id);

create table waits (
    id                uuid primary key,
    instance_id       uuid        not null references instances (id),
    step              text        not null,
    event             text        not null,
    correlation_key   text,
    correlation_value text,
    expires_at        timestamp with time zone,
    status            text        not null, -- OPEN | DONE
    created_at        timestamp with time zone not null default now()
);
create index waits_open_event on waits (event);
create index waits_open_expiry on waits (expires_at);

-- Append-only history: the source of truth for timelines, audit and (later) rewind.
create table events (
    id          bigint generated by default as identity primary key,
    instance_id uuid        not null references instances (id),
    type        text        not null,
    step        text,
    outcome     text,
    actor       text,
    payload     jsonb       not null,
    at          timestamp with time zone not null
);
create index events_instance on events (instance_id, id);
